def bubble_sort(arr):
    """
    冒泡排序算法

    原理：重复遍历待排序列表，依次比较相邻元素，
    如果顺序错误就交换它们。每一轮遍历会将当前未排序部分的最大值"冒泡"到末尾。

    时间复杂度：
        - 最优：O(n)   —— 列表已经有序，只需一轮遍历
        - 最差：O(n²)  —— 列表完全逆序
        - 平均：O(n²)
    空间复杂度：O(1) —— 只使用了常数级别的额外空间
    稳定性：稳定排序 —— 相等元素的相对顺序不会改变
    """
    n = len(arr)

    # 外层循环：控制排序的轮数
    # 总共需要 n-1 轮，因为每轮确定一个元素的最终位置
    for i in range(n - 1):

        # swapped 标志位用于优化：
        # 如果某一轮遍历中没有发生任何交换，说明列表已经有序，可以提前结束
        swapped = False

        # 内层循环：在未排序的部分中，依次比较相邻的两个元素
        # 每完成一轮，末尾就多一个已排序的元素，所以上界是 n - 1 - i
        for j in range(n - 1 - i):

            # 比较相邻元素：如果前一个比后一个大，则交换
            if arr[j] > arr[j + 1]:
                # Python 的多重赋值语法，一行完成交换，无需临时变量
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                # 记录本轮发生了交换
                swapped = True

        # 如果本轮没有发生任何交换，说明列表已完全有序，提前退出
        if not swapped:
            break

    return arr


# ===== 测试 =====
if __name__ == "__main__":
    test_cases = [
        [64, 34, 25, 12, 22, 11, 90],  # 普通无序列表
        [1, 2, 3, 4, 5],                # 已经有序（触发提前退出优化）
        [5, 4, 3, 2, 1],                # 完全逆序（最差情况）
        [1],                             # 单元素
        [],                              # 空列表
    ]

    for case in test_cases:
        original = case.copy()
        result = bubble_sort(case)
        print(f"{original} -> {result}")
